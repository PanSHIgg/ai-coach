def _adjust(method: str, cal: float, p: float, f: float, c: float) -> tuple[float, float, float, float]:
    """按固定规则计算变体营养（确定性）。"""
    if method == "（榨汁）":
        factor = DILUTE[method]
        cal, p, f, c = cal * factor, p * 0.8, f * factor, c * factor
    elif method in BAKE:
        cal, p, f = cal * 1.1, p * 1.05, f * 1.05
    elif method in OIL_ADD:
        oil = OIL_ADD[method]
        f += oil
        cal += oil * 9.0
    return round(cal, 1), round(p, 2), round(f, 2), round(c, 2)


def build_food_rows() -> list[tuple]:
    rows: list[tuple] = []
    seen: set[str] = set()

    def add(name: str, category: str, cal, p, f, c, gi, is_standard: bool) -> bool:
        name = name.strip()
        if not name or name in seen or len(name) > 128:
            return False
        seen.add(name)
        rows.append((name, category, round(float(cal), 1), round(float(p), 2),
                     round(float(f), 2), round(float(c), 2), gi, is_standard))
        return True

    # 3.1 基础食物行 + 烹饪/份量变体
    for category, foods in BASE.items():
        methods = FOOD_METHODS.get(category, [])
        for name, cal, p, f, c, gi in foods:
            is_std = name in STANDARD_FOODS
            add(name, category, cal, p, f, c, gi, is_std)
            for m in methods:
                if m.startswith("（"):
                    variant_name = f"{name}{m}"
                    ncal, np_, nf, nc = cal, p, f, c  # 份量规格：每 100g 一致
                else:
                    if name.startswith(m):  # 避免「水煮水煮蛋」类重复
                        continue
                    variant_name = f"{m}{name}"
                    ncal, np_, nf, nc = _adjust(m, cal, p, f, c)
                add(variant_name, category, ncal, np_, nf, nc, gi, False)

    # 3.2 确定性补量：不足 TARGET_TOP 时按固定顺序补「份量规格」变体
    bases: list[tuple] = [(cat, *food) for cat, foods in BASE.items() for food in foods]
    idx = 0
    while len(rows) < TARGET_TOP and idx < len(bases) * 4:
        cat, name, cal, p, f, c, gi = bases[idx % len(bases)]
        for suffix in ("（小份）", "（大份）"):
            if len(rows) >= TARGET_TOP:
                break
            add(f"{name}{suffix}", cat, cal, p, f, c, gi, False)
        idx += 1

    return rows


def build_alias_rows(food_names: set[str]) -> list[tuple]:
    """生成 (food_name, alias)，保证别名全局唯一且 food_name 存在。"""
    aliases: dict[str, str] = {}  # alias -> food_name
    order: list[tuple] = []
    missing_food: list[str] = []
    dup_alias: list[str] = []
    for food_name, alias_list in ALIAS_SPEC.items():
        if food_name not in food_names:
            missing_food.append(food_name)
            continue
        for alias in alias_list:
            alias = alias.strip()
            if not alias or len(alias) > 128:
                continue
            if alias in aliases:
                if aliases[alias] != food_name:
                    dup_alias.append(alias)
                continue
            aliases[alias] = food_name
            order.append((food_name, alias))
    if missing_food:
        print(f"[warn] 别名表引用了基础表不存在的食物，已跳过：{sorted(set(missing_food))}")
    if dup_alias:
        print(f"[warn] 别名重复（已保留首次），跳过：{sorted(set(dup_alias))}")
    return order


def write_food_csv(rows: list[tuple]) -> None:
    with open(FOOD_CSV, "w", newline="", encoding="utf-8") as fp:
        w = csv.writer(fp)
        w.writerow(["name", "category", "calories_100g", "protein_100g",
                    "fat_100g", "carb_100g", "gi", "is_standard"])
        for name, category, cal, p, f, c, gi, is_std in rows:
            w.writerow([name, category, f"{cal:.1f}", f"{p:.2f}", f"{f:.2f}",
                        f"{c:.2f}", "" if gi is None else int(gi),
                        "true" if is_std else "false"])


def write_alias_csv(rows: list[tuple]) -> None:
    with open(ALIAS_CSV, "w", newline="", encoding="utf-8") as fp:
        w = csv.writer(fp)
        w.writerow(["food_name", "alias"])
        for food_name, alias in rows:
            w.writerow([food_name, alias])


def main() -> int:
    rows = build_food_rows()
    if len(rows) < TARGET_MIN:
        print(f"错误：生成食物行数 {len(rows)} < {TARGET_MIN}", file=sys.stderr)
        return 1

    food_names = {r[0] for r in rows}
    alias_rows = build_alias_rows(food_names)

    # 校验：全部 is_standard 食物须被别名覆盖
    covered = {fn for fn, _ in alias_rows}
    uncovered = sorted(STANDARD_FOODS - covered)
    if uncovered:
        print(f"错误：is_standard 食物未被别名覆盖：{uncovered}", file=sys.stderr)
        return 1

    write_food_csv(rows)
    write_alias_csv(alias_rows)

    std_cnt = sum(1 for r in rows if r[7])
    print(f"food_full.csv: {len(rows)} 行（is_standard={std_cnt}）-> {FOOD_CSV}")
    print(f"food_alias_full.csv: {len(alias_rows)} 行 -> {ALIAS_CSV}")
    return 0


if __name__ == "__main__":
    sys.exit(main())